"""Verificação opcional: requer playwright e Microsoft Edge instalado."""
import json
from pathlib import Path
import tempfile
import threading
from PIL import Image, ImageDraw, ImageFont

from playwright.sync_api import sync_playwright, expect
import Testes as app


def main():
    with tempfile.TemporaryDirectory() as folder:
        app.DB = Path(folder) / 'test.sqlite3'
        app.CONFIG = Path(folder) / 'acesso.json'
        app.CONFIG.write_text(json.dumps({'salt': 'test', 'hash': app.digest('teste-local-123', 'test')}))
        app.initialize()
        server = app.ThreadingHTTPServer(('127.0.0.1', 0), app.Handler)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            with sync_playwright() as p:
                browser = p.chromium.launch(channel='msedge', headless=True)
                page = browser.new_page(viewport={'width': 1366, 'height': 900})
                errors = []
                page.on('pageerror', lambda error: errors.append(str(error)))
                page.goto(f'http://127.0.0.1:{server.server_port}')
                page.locator('#senha').fill('teste-local-123')
                page.locator('#loginForm button').click()
                expect(page.locator('#dashboardView')).to_be_visible()
                expect(page.locator('#dashboardOpening')).to_be_visible()
                expect(page.locator('#initialBalanceForm')).not_to_be_visible()
                page.locator('#tabEntries').click()
                expect(page.locator('#saveInitial')).to_be_enabled()
                page.locator('#initialMonth').fill('2026-06')
                page.locator('#initialBalance').fill('-1,56')
                page.locator('#saveInitial').click()
                expect(page.locator('#initialBalance')).to_have_attribute('readonly', '')
                page.locator('#tabEntries').click()
                page.get_by_role('button', name='Cadastrar ofertas', exact=True).click()
                page.locator('#offerName').fill('Culto de oração e ensino')
                page.locator('#saveOffer').click()
                expect(page.locator('#offerRows')).to_contain_text('Culto de oração e ensino')
                page.locator('#closeOffers').click()
                page.locator('#new').click()
                page.locator('#tipo').select_option('oferta')
                expect(page.locator('#offerLabel')).to_be_visible()
                page.locator('#offerSelect').select_option(label='Culto de oração e ensino')
                page.locator('#data').fill('2026-06-02')
                page.locator('#pessoa').fill('Maria da Silva')
                page.locator('#valor').fill('29,50')
                page.locator('#save').click()
                expect(page.locator('#rows')).to_contain_text('Culto de oração e ensino / Maria da Silva')
                page.locator('#members').click()
                page.locator('#memberCode').fill('001')
                page.locator('#memberName').fill('João da Silva')
                page.locator('#saveMember').click()
                expect(page.locator('#memberRows')).to_contain_text('João da Silva')
                page.locator('#closeMembers').click()
                page.locator('#new').click()
                page.locator('#codigo').fill('001')
                expect(page.locator('#pessoa')).to_have_value('João da Silva')
                page.locator('#data').fill('2026-06-02')
                page.locator('#valor').fill('185,00')
                page.locator('#save').click()
                expect(page.locator('#rows')).to_contain_text('João da Silva')
                page.locator('#tabExpenses').click()
                expect(page.locator('#members')).not_to_be_visible()
                expect(page.locator('#new')).not_to_be_visible()
                expect(page.get_by_role('button', name='Cadastrar ofertas', exact=True)).not_to_be_visible()
                page.locator('#newExpense').click()
                receipt = Path(folder) / 'nota-teste.png'
                picture = Image.new('RGB', (1000, 900), 'white')
                draw = ImageDraw.Draw(picture)
                font = ImageFont.truetype('C:/Windows/Fonts/arial.ttf', 38)
                draw.multiline_text((60,60), 'NOTA DE TESTE - SEM VALOR FISCAL\n\nARROZ 150,00\nLEITE 150,00\n\nTOTAL A PAGAR R$ 300,00', font=font, fill='black', spacing=20)
                picture.save(receipt)
                page.locator('#receiptFile').set_input_files(str(receipt))
                expect(page.locator('#expenseValue')).to_have_value('300,00', timeout=45000)
                expect(page.locator('#expenseDescription')).to_have_value('Alimentos')
                expect(page.locator('#receiptPreview')).to_be_visible()
                page.locator('#expenseDate').fill('2026-06-03')
                page.locator('#expenseDescription').fill('Alimentos - cozinha da igreja')
                page.locator('#expenseValue').fill('300,00')
                page.locator('#saveExpense').click()
                expect(page.locator('#expenseTotal')).to_contain_text('300,00')
                page.locator('#expensePrint').click()
                page.wait_for_url('**/relatorio-despesas?mes=2026-06')
                expect(page.locator('.paper')).to_contain_text('CRÉDITO')
                expect(page.locator('.paper')).to_contain_text('Alimentos - cozinha da igreja')
                page.get_by_role('link', name='Voltar ao sistema').click()
                page.locator('#tabEntries').click()
                page.locator('#entriesMonth').fill('2026-06')
                page.locator('#entriesMonth').dispatch_event('change')
                page.locator('#print').click()
                expect(page.locator('#openingBalance')).to_be_enabled()
                expect(page.locator('#openingBalance')).to_have_attribute('readonly', '')
                expect(page.locator('#openingBalance')).to_have_value('-1,56')
                expect(page.locator('#monthExpenses')).to_have_value('300,00')
                expect(page.locator('#monthExpenses')).to_have_attribute('readonly', '')
                page.locator('#generateReport').click()
                page.wait_for_url('**/relatorio?mes=2026-06')
                expect(page.locator('.summary')).to_contain_text('-R$ 87,06')
                expect(page.locator('.offer')).to_contain_text('OFERTA - CULTO DE ORAÇÃO E ENSINO / MARIA DA SILVA')
                output = Path('.verificacao')
                output.mkdir(exist_ok=True)
                page.screenshot(path=str(output / 'relatorio.png'), full_page=True)
                page.pdf(path=str(output / 'relatorio.pdf'), format='A4', print_background=True, prefer_css_page_size=True)
                page.get_by_role('link', name='Voltar ao sistema').click()
                expect(page.locator('#dashboardView')).to_be_visible()
                page.locator('#dashboardMonth').fill('2026-07')
                page.locator('#dashboardMonth').dispatch_event('change')
                expect(page.locator('#dashboardOpening')).to_contain_text('87,06')
                page.locator('#dashboardMonth').fill('2026-06')
                page.locator('#dashboardMonth').dispatch_event('change')
                expect(page.locator('#dashIncome')).to_contain_text('214,50')
                page.screenshot(path=str(output / 'painel.png'), full_page=True)
                page.locator('#tabEntries').click()
                page.locator('#entriesMonth').fill('2026-06')
                page.locator('#entriesMonth').dispatch_event('change')
                expect(page.locator('#rows')).to_contain_text('João da Silva')
                page.locator('#print').click()
                page.locator('#closingMonth').fill('2026-06')
                page.locator('#closingMonth').dispatch_event('change')
                expect(page.locator('#monthExpenses')).to_have_value('300,00')
                expect(page.locator('#openingBalance')).to_have_value('-1,56')
                page.locator('#closeClosing').click()
                page.set_viewport_size({'width': 390, 'height': 844})
                page.locator('#tabDashboard').click()
                expect(page.locator('#dashboardView')).to_be_visible()
                page.screenshot(path=str(output / 'painel-celular.png'), full_page=True)
                real_note = Path('.verificacao/nota-recebida.png')
                if real_note.exists():
                    page.locator('#tabExpenses').click()
                    page.locator('#newExpense').click()
                    page.locator('#receiptFile').set_input_files(str(real_note))
                    expect(page.locator('#expenseValue')).to_have_value('181,43', timeout=60000)
                    expect(page.locator('#expenseDescription')).to_have_value('Alimentos / Higiene pessoal')
                    page.locator('#cancelExpense').click()
                page.locator('#tabEntries').click()
                count = page.locator('#rows .delete-button').count()
                assert count > 0
                page.once('dialog', lambda dialog: dialog.dismiss())
                page.locator('#rows .delete-button').first.click()
                expect(page.locator('#rows .delete-button')).to_have_count(count)
                page.once('dialog', lambda dialog: dialog.accept())
                page.locator('#rows .delete-button').first.click()
                expect(page.locator('#rows .delete-button')).to_have_count(count - 1)
                page.locator('#tabExpenses').click()
                page.locator('#expenseMonth').fill('2026-06')
                page.locator('#expenseMonth').dispatch_event('change')
                expect(page.locator('#expenseRows .delete-button')).to_have_count(1)
                page.once('dialog', lambda dialog: dialog.accept())
                page.locator('#expenseRows .delete-button').click()
                expect(page.locator('#expenseRows .delete-button')).to_have_count(0)
                expect(page.locator('#expenseTotal')).to_contain_text('0,00')
                page.locator('#tabEntries').click()
                page.get_by_role('button', name='Cadastrar ofertas', exact=True).click()
                expect(page.locator('#offerName')).to_be_visible()
                assert not errors, errors
                browser.close()
                print('OK: cadastro, oferta, dizimista, fechamento, persistência, PDF e tela móvel.')
        finally:
            server.shutdown()
            server.server_close()
            thread.join()


if __name__ == '__main__':
    main()
